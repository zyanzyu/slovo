import { webkit } from 'playwright';
import assert from 'node:assert/strict';
const browser = await webkit.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await page.goto('http://127.0.0.1:4173/library/daily', { waitUntil: 'networkidle' });
await page.locator('.word-row').first().click();
await page.waitForTimeout(300);
assert.equal(await page.locator('.word-editor-modal').count(), 1);
await page.locator('.word-editor-modal .modal-footer .danger-text').click();
await page.waitForTimeout(300);
assert.equal(await page.locator('.modal-small').count(), 1);
assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden');
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
assert.equal(await page.locator('.modal-small').count(), 0, 'confirm closed');
assert.equal(await page.locator('.word-editor-modal').count(), 1, 'editor still open');
assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden', 'body still locked');
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
assert.equal(await page.locator('.word-editor-modal').count(), 0, 'editor closed');
assert.equal(await page.evaluate(() => document.body.style.overflow), '', 'body unlocked');
console.log('✓ Esc 只关闭最上层弹窗，滚动锁正确释放');
await browser.close();
